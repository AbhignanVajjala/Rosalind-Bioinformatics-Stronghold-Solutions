#The total number of signed permutations of n is 2^n *n!

import math

t_sp=(math.pow(2,n))*math.factorial(n)

print(int(t_sp))

import itertools

pairs=[]

for i in range(1,n+1):
  pairs.append((-i,i))

combinations=list(itertools.product(*pairs))

for x in combinations:
  for y in itertools.permutations(x):
    print(*y)

